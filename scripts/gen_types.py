"""Generate TypeScript types from the Python schema. One source of truth.

    python scripts/gen_types.py        # writes web/src/types.generated.ts

Run it whenever api/schema.py changes. Phase 02's gate is that the frontend
cannot compile against a stale contract, and that only holds if this file is
the only way types reach the UI — never hand-edit the output.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "src" / "types.generated.ts"

sys.path.insert(0, str(ROOT))
from api.schema import (  # noqa: E402
    Done, Failed, GroundedTriageResult, LiveCandidate, RunStarted, StepStarted,
    ToolCall, ToolCalled, ToolReturned, Totals, TriageResult, Usage,
)

LIVE_MEMBERS = [RunStarted, StepStarted, Usage, ToolCalled, ToolReturned, Done, Failed]
LIVE_PARTS = [Totals, LiveCandidate]


def live_defs() -> dict:
    """The live-run events as $defs, each titled by its class name, plus the LiveEvent union.

    Every model is rendered with refs pointing at the shared $defs, and Done.result
    points at the GroundedTriageResult already emitted above rather than a copy.
    """
    defs: dict = {}
    for model in LIVE_PARTS + LIVE_MEMBERS:
        schema = model.model_json_schema(ref_template="#/$defs/{model}")
        schema.pop("$defs", None)
        schema["title"] = model.__name__
        # Property titles would each become a numbered alias (Type3, Seq5, ...);
        # without them the fields are typed inline and only the named types remain.
        for prop in schema["properties"].values():
            prop.pop("title", None)
        defs[model.__name__] = schema
    defs["Done"]["properties"]["result"] = {"$ref": "#/$defs/GroundedTriageResult"}
    defs["LiveEvent"] = {
        "title": "LiveEvent",
        "oneOf": [{"$ref": f"#/$defs/{m.__name__}"} for m in LIVE_MEMBERS],
    }
    return defs



def main() -> None:
    schema = TriageResult.model_json_schema()
    schema["title"] = "TriageResult"

    # GroundedTriageResult subclasses TriageResult, so it is emitted the same
    # way: TriageResult & { the fields it adds }. Generating it as a second
    # standalone schema would re-declare every shared alias (Reasoning1, ...).
    sub = GroundedTriageResult.model_json_schema()
    added = {k: v for k, v in sub["properties"].items() if k not in schema["properties"]}
    schema["$defs"] = {
        "GroundedTriageResult": {
            "title": "GroundedTriageResult",
            "description": sub.get("description", ""),
            "allOf": [
                {"$ref": "#"},
                {"type": "object", "properties": added, "required": sorted(added),
                 "additionalProperties": False},
            ],
        },
        # Not reachable from TriageResult; emitted the same way so the UI can import it.
        "ToolCall": ToolCall.model_json_schema(),
        **live_defs(),
    }

    try:
        generated = subprocess.run(
            ["npx", "--yes", "json-schema-to-typescript", "--stdin", "--bannerComment", "",
             "--unreachableDefinitions"],
            input=json.dumps(schema), capture_output=True, text=True,
            cwd=ROOT / "web", check=True,
        ).stdout
    except FileNotFoundError:
        raise SystemExit("npx not found — install Node, or run this from web/")
    except subprocess.CalledProcessError as exc:
        raise SystemExit(f"json-schema-to-typescript failed:\n{exc.stderr}")

    OUT.write_text(
        "// GENERATED by scripts/gen_types.py from api/schema.py — do not edit.\n"
        "// Regenerate after any change to a contract in api/schema.py.\n\n" + generated
    )
    print(f"→ {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
